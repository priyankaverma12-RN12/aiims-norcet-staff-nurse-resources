'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const source=fs.readFileSync(require('node:path').join(__dirname,'app.js'),'utf8');
const boundary=source.indexOf('async function read(');
assert(boundary>0);
const {safe,route,normalize,internalPath,repo}=new Function('document','location',source.slice(0,boundary)+';return {safe,route,normalize,internalPath,repo};')({}, {search:''});
const base='Chapters/Eye-and-ENT-Nursing/README.md';
assert.equal(internalPath(normalize('MCQs',base)),'Chapters/Eye-and-ENT-Nursing/MCQs/');
assert.equal(internalPath(normalize('MCQs/',base)),'Chapters/Eye-and-ENT-Nursing/MCQs/');
assert.equal(internalPath(normalize('Concepts/A%20B.md#topic',base)),'Chapters/Eye-and-ENT-Nursing/Concepts/A B.md');
assert.equal(normalize('https://github.com/'+repo+'/blob/main/Chapters/Eye-and-ENT-Nursing/README.md#topic',base).hash,'#topic');
assert.equal(internalPath(normalize('https://github.com/'+repo+'/tree/main/Chapters/Eye-and-ENT-Nursing/MCQs',base)),'Chapters/Eye-and-ENT-Nursing/MCQs/');
assert.equal(internalPath(normalize('Assets/diagram.svg',base)),null);
assert.equal(internalPath(normalize('https://example.com/a.md',base)),null);
assert.equal(safe('Chapters/../README.md'),false);
assert.equal(safe('Chapters/Test/a%2Fb.md'),false);
assert.equal(safe('Chapters/Test/A, B.md'),true);
assert.equal(safe('Chapters/Test\\evil.md'),false);
assert.equal(route('Chapters/Test/A B.md','#topic'),'?doc=Chapters%2FTest%2FA%20B.md#topic');
console.log('12 navigation assertions passed');
